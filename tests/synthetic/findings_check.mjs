import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../../vulnassess/ui/static/findings-model.js', import.meta.url), 'utf8');
const {filterFindings, displayEpss, displayNumber, kevLabel} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const rows = [{title:'<script>literal</script>', host:'127.0.0.1', port:8787, tool:'nikto', band:'Low', cves:[]}, {title:'Redis condition', host:'127.0.0.1', port:6379, band:'Critical', cves:[{id:'CVE-2022-0543', kev:true}]}];
assert.equal(filterFindings(rows).length, 2);
assert.equal(filterFindings(rows, {query:'6379'})[0].title, 'Redis condition');
assert.equal(filterFindings(rows, {query:'cve-2022-0543'}).length, 1);
assert.equal(filterFindings(rows, {band:'Low'}).length, 1);
assert.equal(filterFindings(rows, {kev:true}).length, 1);
assert.equal(filterFindings(rows, {query:'no match'}).length, 0);
assert.equal(kevLabel([]), 'Unknown');
assert.equal(kevLabel([{kev:null}]), 'Unknown');
assert.equal(kevLabel([{kev:false}]), 'Not listed');
assert.equal(displayNumber(0), '0');
assert.equal(displayNumber(null), '—');
assert.equal(displayEpss(.99351), '99.351%');
assert.equal(displayEpss(null), '—');
console.log('findings model checks passed');
